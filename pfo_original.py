# Classification Accuracy , Precision and Recall
def classification_accuracy(y_actual, y_hat):
        TP = 0
        FP = 0
        TN = 0
        FN = 0

        for i in range(len(y_hat)): 
            if y_actual[i]==y_hat[i]==1:
                TP += 1
            if y_hat[i]==1 and y_actual[i]!=y_hat[i]:
                FP += 1
            if y_actual[i]==y_hat[i]==0:
                TN += 1
            if y_hat[i]==0 and y_actual[i]!=y_hat[i]:
                FN += 1
        
        
        class_acc = float((TP+TN)) / float((TP+FP+TN+FN))
        
        if TP == 0 and FN == 0 :
            recall = 0
        else:
            recall  = float(TP) / float(TP + FN)
        
        if TP == 0 and FP == 0:
            precision = 0
        else:
            precision = float(TP) / float( TP + FP )         
        
        if TN == 0 and FP == 0 :
          specificity = 0
        else:
          specificity = float(TN) / float(TN + FP)  

        f1_score = float(2 * precision * recall) / float(precision + recall)

        if TP == 0 and TN == 0 and FN ==0 and FP == 0 :
          kappa = 0
        else:
          kappa = float(2 * (TP * TN - FN * FP)) / float((TP + FP) * (FP + TN) + (TP + FN) * (FN + TN))

        if TP == 0 and TN == 0 and FN ==0 and FP == 0 :
          MCC = 0
        else:
          MCC = float(TP * TN - FN * FP) / float(math.sqrt((TP + FP) * (FP + TN) * (TP + FN) * (FN + TN)))    

        return (class_acc,specificity, recall, precision,f1_score,kappa,MCC)

